% 复化辛普森求积公式

%% 1. 定义被积函数、积分区间和节点数
% 被积函数1：sin(x)./x（x=0时赋值为1）
f = @(x) (x)./(4+x.^2);  
% 被积函数2：exp(x)（可替换测试）
% f = @(x) exp(x);  

a = 0;  % 积分下限
b = 1;  % 积分上限
n = 9;  % 求积节点数（子区间数为n-1，需为偶数）

%% 2. 计算节点、步长和函数值
x = linspace(a, b, n);  % 生成n个等距节点
h = x(2) - x(1);        % 子区间长度
y = f(x);               % 节点处函数值
%y(1) = 1;               % 处理sin(0)/0的情况，测试exp(x)时注释此行

%% 3. 复化辛普森公式计算
x_mid = (x(1:n-1) + x(2:n)) / 2;  % 子区间中点
y_mid = f(x_mid);                 % 中点处函数值
I_simpson = (y(1) + 4 * sum(y_mid) + 2 * sum(y(2:n-1)) + y(end)) * h / 6;

%% 4. 输出结果
fprintf('复化辛普森求积：%.10f\n', I_simpson);